export type MessageKey = keyof typeof zh;

const catalogs: Record<AppLocale, typeof zh> = { "zh-CN": zh, en };

export function normalizeLocale(value: string | undefined | null): AppLocale {
  return value === "en" ? "en" : "zh-CN";
}

export function applyLocale(language: string) {
  document.documentElement.lang = normalizeLocale(language);
}

export function translate(locale: AppLocale, key: MessageKey, vars?: Record<string, string | number>) {
  let text: string = catalogs[locale][key];
  if (!vars) return text;
  for (const [name, value] of Object.entries(vars)) {
    text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}

export function useI18n() {
  const store = useSettingsStore();
  const locale = computed(() => normalizeLocale(store.settings.language));
  function t(key: MessageKey, vars?: Record<string, string | number>) {
    return translate(locale.value, key, vars);
  }
  return { t, locale };
}
